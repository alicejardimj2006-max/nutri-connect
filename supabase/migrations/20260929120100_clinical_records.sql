-- Publicar um plano arquiva o ativo anterior do mesmo profissional.
create or replace function public.publish_meal_plan(p_plan uuid)
returns public.meal_plans
language plpgsql security definer set search_path = public as $$
declare
  m public.meal_plans;
begin
  if not public.can_edit_meal_plan(p_plan) then
    raise exception 'Plano não encontrado' using errcode = '42501';
  end if;
  select * into m from public.meal_plans where id = p_plan;
  update public.meal_plans set status = 'arquivado'
   where patient_id = m.patient_id and professional_id = m.professional_id
     and status = 'ativo' and id <> p_plan;
  update public.meal_plans
     set status = 'ativo', published_at = now(), starts_on = coalesce(starts_on, current_date)
   where id = p_plan
  returning * into m;
  return m;
end;
$$;

-- Duplicar um plano (base para uma nova versão).
create or replace function public.duplicate_meal_plan(p_plan uuid)
returns public.meal_plans
language plpgsql security definer set search_path = public as $$
declare
  src public.meal_plans;
  dst public.meal_plans;
  meal record;
  new_meal uuid;
  item_map jsonb := '{}'::jsonb;
  it record;
  new_item uuid;
begin
  if not public.can_edit_meal_plan(p_plan) then
    raise exception 'Plano não encontrado' using errcode = '42501';
  end if;
  select * into src from public.meal_plans where id = p_plan;
  insert into public.meal_plans (
    patient_id, professional_id, title, status, target_kcal, target_protein_g,
    target_carbs_g, target_fat_g, guidelines
  ) values (
    src.patient_id, src.professional_id, src.title || ' (cópia)', 'rascunho', src.target_kcal,
    src.target_protein_g, src.target_carbs_g, src.target_fat_g, src.guidelines
  ) returning * into dst;

  for meal in select * from public.meal_plan_meals where plan_id = p_plan order by position loop
    insert into public.meal_plan_meals (plan_id, name, time_of_day, position, notes)
    values (dst.id, meal.name, meal.time_of_day, meal.position, meal.notes)
    returning id into new_meal;
    -- Itens principais primeiro, depois substituições apontando para os novos ids.
    for it in select * from public.meal_plan_items
               where meal_id = meal.id order by (substitute_of is not null), position loop
      insert into public.meal_plan_items (
        meal_id, substitute_of, food_id, food_name, quantity_g, household_measure,
        kcal, protein_g, carbs_g, fat_g, position, notes
      ) values (
        new_meal, (item_map ->> it.substitute_of::text)::uuid, it.food_id, it.food_name,
        it.quantity_g, it.household_measure, it.kcal, it.protein_g, it.carbs_g, it.fat_g,
        it.position, it.notes
      ) returning id into new_item;
      item_map := item_map || jsonb_build_object(it.id::text, new_item);
    end loop;
  end loop;
  return dst;
end;
$$;

