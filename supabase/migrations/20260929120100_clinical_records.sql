-- Planos: paciente vê publicados; profissional autor vê tudo e edita com vínculo ativo.
create or replace function public.can_read_meal_plan(p_plan uuid)
returns boolean language sql stable security definer set search_path = public as $$
  select exists (
    select 1 from public.meal_plans m
     where m.id = p_plan
       and (m.professional_id = auth.uid() or (m.patient_id = auth.uid() and m.status <> 'rascunho'))
  );
$$;
create or replace function public.can_edit_meal_plan(p_plan uuid)
returns boolean language sql stable security definer set search_path = public as $$
  select exists (
    select 1 from public.meal_plans m
     where m.id = p_plan and m.professional_id = auth.uid()
       and public.has_active_link(m.patient_id)
  );
$$;

create policy "meal_plans: leitura" on public.meal_plans
  for select to authenticated using (
    professional_id = auth.uid() or (patient_id = auth.uid() and status <> 'rascunho')
  );
create policy "meal_plans: profissional cria" on public.meal_plans
  for insert to authenticated with check (
    professional_id = auth.uid() and public.has_active_link(patient_id)
  );
create policy "meal_plans: profissional edita" on public.meal_plans
  for update to authenticated
  using (professional_id = auth.uid() and public.has_active_link(patient_id))
  with check (professional_id = auth.uid());
create policy "meal_plans: profissional apaga rascunho" on public.meal_plans
  for delete to authenticated using (professional_id = auth.uid() and status = 'rascunho');

create policy "meal_plan_meals: leitura" on public.meal_plan_meals
