create or replace function public.storage_owner(p_name text)
returns uuid language sql immutable as $$
  select case
    when (storage.foldername(p_name))[1] ~ '^[0-9a-f-]{36}$' then (storage.foldername(p_name))[1]::uuid
  end;
$$;

create policy "avatars: leitura pública" on storage.objects
  for select to anon, authenticated using (bucket_id = 'avatars');
create policy "avatars: dono envia" on storage.objects
  for insert to authenticated with check (bucket_id = 'avatars' and public.storage_owner(name) = auth.uid());
create policy "avatars: dono atualiza" on storage.objects
  for update to authenticated using (bucket_id = 'avatars' and public.storage_owner(name) = auth.uid());
create policy "avatars: dono apaga" on storage.objects
  for delete to authenticated using (bucket_id = 'avatars' and public.storage_owner(name) = auth.uid());

create policy "verification-docs: dono ou admin lê" on storage.objects
  for select to authenticated using (
    bucket_id = 'verification-docs'
    and (public.storage_owner(name) = auth.uid() or public.is_platform_admin())
  );
create policy "verification-docs: dono envia" on storage.objects
  for insert to authenticated with check (
    bucket_id = 'verification-docs' and public.storage_owner(name) = auth.uid()
  );

create policy "patient-files: leitura" on storage.objects
  for select to authenticated using (
    bucket_id in ('patient-files', 'diary-photos')
    and (public.storage_owner(name) = auth.uid() or public.has_active_link(public.storage_owner(name)))
  );
create policy "patient-files: envio" on storage.objects
  for insert to authenticated with check (
    (bucket_id = 'patient-files'
      and (public.storage_owner(name) = auth.uid() or public.has_active_link(public.storage_owner(name))))
    or (bucket_id = 'diary-photos' and public.storage_owner(name) = auth.uid())
  );
create policy "patient-files: remoção" on storage.objects
  for delete to authenticated using (
    bucket_id in ('patient-files', 'diary-photos')
    and public.storage_owner(name) = auth.uid()
  );

create policy "chat-attachments: participantes leem" on storage.objects
  for select to authenticated using (
    bucket_id = 'chat-attachments'
    and auth.uid()::text in ((storage.foldername(name))[1], (storage.foldername(name))[2])
  );
create policy "chat-attachments: participantes enviam" on storage.objects
  for insert to authenticated with check (
    bucket_id = 'chat-attachments'
    and auth.uid()::text in ((storage.foldername(name))[1], (storage.foldername(name))[2])
    and public.has_active_link(
      public.storage_owner(name),
      case when (storage.foldername(name))[2] ~ '^[0-9a-f-]{36}$'
        then (storage.foldername(name))[2]::uuid end
    )
  );

