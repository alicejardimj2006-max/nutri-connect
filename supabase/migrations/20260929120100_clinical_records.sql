-- =============================================================================
-- NutriConnect — prontuário, antropometria, alimentos, plano alimentar,
-- metas, diário alimentar, mensagens e documentos.
--
-- Regra geral de acesso:
--   * o paciente lê tudo o que é dele (exceto notas clínicas privadas e rascunhos);
--   * o profissional escreve com vínculo ativo e continua lendo o que registrou
--     mesmo após o fim do vínculo (guarda de prontuário);
--   * dados gerados pelo próprio paciente (diário, metas, medidas, exames) ficam
--     visíveis a todos os profissionais com vínculo ativo.
-- =============================================================================

create type public.meal_plan_status as enum ('rascunho', 'ativo', 'arquivado');
create type public.document_kind as enum ('exame', 'documento', 'plano', 'outro');

-- ---------------------------------------------------------------------------
-- Anamnese (uma por par paciente/profissional, estrutura em JSON tipada no app)
-- ---------------------------------------------------------------------------
create table public.anamneses (
  id uuid primary key default gen_random_uuid(),
  patient_id uuid not null references public.profiles (id) on delete cascade,
  professional_id uuid not null references public.professionals (user_id) on delete cascade,
  data jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (patient_id, professional_id)
);
create trigger anamneses_updated_at before update on public.anamneses
  for each row execute function public.set_updated_at();

