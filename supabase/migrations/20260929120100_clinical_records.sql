-- ---------------------------------------------------------------------------
-- Antropometria
-- ---------------------------------------------------------------------------
create table public.anthropometrics (
  id uuid primary key default gen_random_uuid(),
  patient_id uuid not null references public.profiles (id) on delete cascade,
  -- null = autorregistro do paciente (apenas peso/cintura).
  professional_id uuid references public.professionals (user_id) on delete set null,
  appointment_id uuid references public.appointments (id) on delete set null,
  measured_at date not null default current_date,
  weight_kg numeric(5, 2) check (weight_kg between 1 and 500),
  height_cm numeric(5, 1) check (height_cm between 30 and 260),
  -- Circunferências (cm): waist, hip, arm, calf, neck, chest, thigh, abdomen.
  circumferences jsonb not null default '{}'::jsonb,
  -- Dobras cutâneas (mm): triceps, biceps, subscapular, suprailiac, abdominal, thigh, chest, midaxillary.
  skinfolds jsonb not null default '{}'::jsonb,
  body_fat_protocol text, -- jp3, jp7, durnin, bioimpedancia, manual
  body_fat_pct numeric(4, 1) check (body_fat_pct between 1 and 80),
  activity_factor numeric(3, 2),
  bmr_kcal integer,
  tdee_kcal integer,
  bmr_formula text, -- harris_benedict, mifflin, fao_who
  notes text,
  created_at timestamptz not null default now()
);
create index anthropometrics_patient_idx on public.anthropometrics (patient_id, measured_at);

-- ---------------------------------------------------------------------------
-- Alimentos (TACO + alimentos próprios do profissional). Valores por 100 g.
-- ---------------------------------------------------------------------------
create table public.foods (
  id bigint generated by default as identity primary key,
  source text not null default 'TACO' check (source in ('TACO', 'custom')),
  source_code text,
  owner_id uuid references public.professionals (user_id) on delete cascade,
  name text not null,
  category text not null,
  kcal numeric(7, 2) not null default 0,
  protein_g numeric(7, 2) not null default 0,
  carbs_g numeric(7, 2) not null default 0,
  fat_g numeric(7, 2) not null default 0,
  fiber_g numeric(7, 2),
  sodium_mg numeric(8, 2),
  calcium_mg numeric(8, 2),
  iron_mg numeric(7, 2),
  -- Medidas caseiras: [{ "name": "colher de sopa", "grams": 25 }]
  household_measures jsonb not null default '[]'::jsonb,
  created_at timestamptz not null default now(),
  check ((source = 'custom') = (owner_id is not null))
);
create extension if not exists pg_trgm with schema extensions;
create index foods_name_trgm_idx on public.foods using gin (lower(name) extensions.gin_trgm_ops);
create unique index foods_source_code_idx on public.foods (source, source_code) where source_code is not null;

